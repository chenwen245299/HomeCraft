void brand_icon(canvas_t *c,unsigned provider,int x,int y,unsigned size)
{
    if(provider==4)provider=2;
    static const uint8_t *small[]={logo0_44,logo1_44,logo2_44,logo3_44};
    static const uint8_t *large[]={logo0_56,logo1_56,logo2_56,logo3_56};
    if(provider>=4) {
        canvas_round_box(c,x+4,y+4,size-8,size-8,8,2);
        canvas_text(c,x+size/2-8,y+size/2-10,"AI",&font16,1,true);
        return;
    }
    if(size!=56) size=44;
    const uint8_t *pixels=size==56?large[provider]:small[provider];
    unsigned stride=(size+7)/8;
    for(unsigned yy=0;yy<size;++yy) for(unsigned xx=0;xx<size;++xx)
        if(pixels[yy*stride+xx/8]&(0x80>>(xx%8))) canvas_pixel(c,x+xx,y+yy,true);
}

static void brand_centered_text(canvas_t *c,int x,int center,const char *text,const bitmap_font_t *font)
{
    int top,bottom;
    if(!canvas_text_ink_bounds(text,font,&top,&bottom)){top=0;bottom=font->height-1;}
    canvas_text(c,x,center-(top+bottom)/2,text,font,1,true);
}
void brand_title(canvas_t *c,unsigned provider,const char *name,int x,int center,unsigned size,int text_room,const bitmap_font_t *preferred,bool compact_suffix)
{
    const char *primary=provider==4 && compact_suffix?"DeepSeek":name;
    const bitmap_font_t *fonts[]={&font_bold32,&font_bold28,&font_bold24,&font_bold20,&font_bold16,&font_bold12};
    const bitmap_font_t *font=preferred;
    // Header typography is fixed; the header drops optional dates to make room.
    // Only compact content cards may reduce their provider name to fit.
    if(compact_suffix) {
        font=&font_bold12;
        for(unsigned i=0;i<6;++i)if(fonts[i]->height<=preferred->height && canvas_text_width(primary,fonts[i],1)<=text_room){font=fonts[i];break;}
    }
    unsigned brand=provider==4?2:provider;
    int icon_top=size,icon_bottom=-1;
    if(brand<4) {
        const uint8_t *small[]={logo0_44,logo1_44,logo2_44,logo3_44};
        const uint8_t *large[]={logo0_56,logo1_56,logo2_56,logo3_56};
        const uint8_t *pixels=size==56?large[brand]:small[brand];unsigned stride=(size+7)/8;
        for(unsigned yy=0;yy<size;++yy)for(unsigned xx=0;xx<size;++xx)if(pixels[yy*stride+xx/8]&(0x80>>(xx%8))){if((int)yy<icon_top)icon_top=yy;if((int)yy>icon_bottom)icon_bottom=yy;}
    }
    if(icon_bottom<icon_top){icon_top=0;icon_bottom=size-1;}
    brand_icon(c,provider,x,center-(icon_top+icon_bottom)/2,size);
    int text_x=x+size+12;
    if(provider==4 && compact_suffix) {
        const bitmap_font_t *secondary=font;
        int width=canvas_text_width(primary,font,1);
        if(width+8+canvas_text_width("Harness",secondary,1)<=text_room) {
            brand_centered_text(c,text_x,center,primary,font);
            brand_centered_text(c,text_x+width+8,center,"Harness",secondary);
        } else {
            int a,b,cc,d;canvas_text_ink_bounds(primary,font,&a,&b);canvas_text_ink_bounds("Harness",secondary,&cc,&d);
            int first=b-a+1,second=d-cc+1,total=first+3+second;
            brand_centered_text(c,text_x,center-total/2+first/2,primary,font);
            brand_centered_text(c,text_x,center-total/2+first+3+second/2,"Harness",secondary);
        }
    } else brand_centered_text(c,text_x,center,name,font);
}
