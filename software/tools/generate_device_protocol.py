#!/usr/bin/env python3
"""Generate matching host/board constants from HomeCraft's public protocol contract."""
import argparse
import json
from pathlib import Path

software = Path(__file__).resolve().parents[1]
workspace = software.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
parser.add_argument('--hardware', help='Generate one registered board; default checks every device-v1 adapter')
args = parser.parse_args()
contract = json.loads((software/'protocol/device-v1.json').read_text())
pages = contract['pages']
assert contract['version'] == 1 and contract['max_plaintext_bytes'] == 480
assert [p['id'] for p in pages] == list(range(len(pages))) and len(pages) <= 15
assert len({p['key'] for p in pages}) == len(pages)
rust = '// Generated by software/tools/generate_device_protocol.py; edit protocol/device-v1.json.\n'
rust += f'pub const PAGES: [(&str, &str); {len(pages)}] = [\n'
for p in pages:
    rust += f'    ({json.dumps(p["key"])}, {json.dumps(p["label"], ensure_ascii=False)}),\n'
rust += f'];\npub const PAGE_MASK_LIMIT: u16 = {1 << len(pages)};\n'
header = '// Generated by HomeCraft; edit software/protocol/device-v1.json.\n#pragma once\n'
header += f'#define HOMECRAFT_PAGE_COUNT {len(pages)}\n'
header += '#define HOMECRAFT_PAGE_NAMES {' + ','.join(json.dumps(p['key']) for p in pages) + '}\n'
header += ''.join(f'#define HOMECRAFT_PAGE_{p["key"].upper()} {p["id"]}\n' for p in pages)
outputs = {software/'mac-app/src/device_pages.rs': rust}
selected = [workspace/args.hardware] if args.hardware else sorted(workspace.glob('*/board.json'))
for candidate in selected:
    board = (candidate.parent if candidate.name == 'board.json' else candidate).resolve()
    assert board.is_relative_to(workspace.resolve()) and (board/'board.json').is_file()
    profile = json.loads((board/'board.json').read_text())['protocol']
    if profile.get('profile') != 'device-v1':
        assert not args.hardware, 'Selected hardware has no device-v1 adapter'
        continue
    board_header = (board/profile['generated_header']).resolve()
    assert board_header.is_relative_to(board)
    outputs[board_header] = header
for path, expected in outputs.items():
    assert path.resolve().is_relative_to(workspace.resolve())
    if args.check:
        assert path.read_text() == expected, f'{path.name} differs; regenerate from HomeCraft contract'
    else:
        path.write_text(expected)
print('HomeCraft protocol constants match Mac and registered adapters.' if args.check else 'Generated Mac and registered-board protocol constants.')
