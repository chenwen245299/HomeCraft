// Generates main/lunar.c from Apple's Chinese calendar: one entry per lunar month start, 2025–2060.
// Run from the board directory: swift tools/generate_lunar.swift
import Foundation

var chinese = Calendar(identifier: .chinese)
chinese.timeZone = TimeZone(identifier: "Asia/Shanghai")!
var gregorian = Calendar(identifier: .gregorian)
gregorian.timeZone = chinese.timeZone
let first = gregorian.date(from: DateComponents(year: 2025, month: 1, day: 1))!
let last = gregorian.date(from: DateComponents(year: 2060, month: 12, day: 31))!
var rows: [String] = []
var day = first
var index = 0
let start = chinese.dateComponents([.month, .day, .isLeapMonth], from: first)
// The first entry anchors 2025-01-01 inside its month: store a negative offset to that month's start.
rows.append("{\(-(start.day! - 1)),\(start.month!),\(start.isLeapMonth! ? 1 : 0)}")
while day <= last {
    let c = chinese.dateComponents([.month, .day, .isLeapMonth], from: day)
    if c.day == 1 && index > 0 { rows.append("{\(index),\(c.month!),\(c.isLeapMonth! ? 1 : 0)}") }
    day = gregorian.date(byAdding: .day, value: 1, to: day)!
    index += 1
}
let source = """
// Generated by tools/generate_lunar.swift from Apple's Chinese calendar (Asia/Shanghai); do not edit.
#include "lunar.h"
#include <stdio.h>
static const struct {short start;unsigned char month,leap;} months[]={
\(rows.joined(separator: ",\n"))
};
// Integer civil-date day count (proleptic Gregorian), so no libc timegm is needed.
static long civil(int y,int m,int d){y-=m<=2;long era=(y>=0?y:y-399)/400;unsigned yoe=(unsigned)(y-era*400),doy=(153*(m+(m>2?-3:9))+2)/5+d-1,doe=yoe*365+yoe/4-yoe/100+doy;return era*146097+(long)doe;}
static int days_since_2025(int y,int m,int d){return (int)(civil(y,m,d)-civil(2025,1,1));}
bool lunar_text(int y,int m,int d,char *out,size_t capacity){
 static const char *names[]={"正","二","三","四","五","六","七","八","九","十","冬","腊"};
 static const char *tens[]={"初","十","廿","三"};static const char *units[]={"十","一","二","三","四","五","六","七","八","九"};
 int n=days_since_2025(y,m,d),i=-1;
 for(unsigned k=0;k<sizeof(months)/sizeof(months[0])&&months[k].start<=n;++k)i=(int)k;
 if(i<0||(unsigned)i+1>=sizeof(months)/sizeof(months[0]))return false;
 int day=n-months[i].start+1;if(day<1||day>30)return false;
 const char *ten=day==10?"初":day==20?"二":day==30?"三":tens[day/10];
 snprintf(out,capacity,"%s%s月%s%s",months[i].leap?"闰":"",names[months[i].month-1],ten,units[day%10]);
 return true;
}

"""
try! source.write(toFile: "main/lunar.c", atomically: true, encoding: .utf8)
print("Generated \(rows.count) lunar month starts (2025-2060).")
