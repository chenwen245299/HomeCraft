#!/usr/bin/env python3
"""Dither a public-domain picture into the six-ink privacy frame (main/privacy.c).

The source image is untrusted input: keep it in its own folder outside the repository and pass its path;
only this script's folder is on the import path (run with `python3 -E`). Only the
dithered frame, a preview PNG and a provenance record (URL, licence note, SHA-256) are written here.
"""
import argparse,hashlib,json
from pathlib import Path
from PIL import Image,ImageEnhance,ImageOps
ROOT=Path(__file__).resolve().parents[1]
# Approximate printed appearance of the inks, used only to choose dither colours; indices match the panel.
PANEL={0:(28,28,32),1:(234,234,228),2:(236,208,36),3:(176,36,40),5:(40,70,164),6:(52,118,72)}
PREVIEW={0:(20,24,27),1:(255,255,250),2:(255,210,0),3:(205,30,45),5:(35,80,185),6:(20,140,65)}
def nearest(r,g,b):
 # Weighted RGB distance ("redmean") is close enough to perceptual for six inks.
 best,key=None,0
 for k,(pr,pg,pb) in PANEL.items():
  m=(r+pr)/2;d=(2+m/256)*(r-pr)**2+4*(g-pg)**2+(2+(255-m)/256)*(b-pb)**2
  if best is None or d<best:best,key=d,k
 return key
def dither(im):
 w,h=im.size;px=[list(map(float,p)) for p in im.getdata()];out=[0]*(w*h)
 for y in range(h):
  # Serpentine scan avoids the diagonal drift of plain Floyd–Steinberg.
  xs=range(w) if y%2==0 else range(w-1,-1,-1);step=1 if y%2==0 else -1
  for x in xs:
   i=y*w+x;r,g,b=(min(255,max(0,v)) for v in px[i]);k=nearest(r,g,b);out[i]=k
   er,eg,eb=r-PANEL[k][0],g-PANEL[k][1],b-PANEL[k][2]
   for dx,dy,f in ((step,0,7/16),(-step,1,3/16),(0,1,5/16),(step,1,1/16)):
    nx,ny=x+dx,y+dy
    if 0<=nx<w and ny<h:
     q=px[ny*w+nx];q[0]+=er*f;q[1]+=eg*f;q[2]+=eb*f
 return out
if __name__=='__main__':
 ap=argparse.ArgumentParser()
 ap.add_argument('image');ap.add_argument('--caption',required=True);ap.add_argument('--source',required=True)
 ap.add_argument('--licence',required=True);ap.add_argument('--focus',type=float,default=0.5,help='vertical crop centre 0..1')
 ap.add_argument('--saturation',type=float,default=1.3);ap.add_argument('--contrast',type=float,default=1.12)
 a=ap.parse_args();raw=Path(a.image).read_bytes()
 im=Image.open(a.image).convert('RGB')
 im=ImageOps.fit(im,(800,480),Image.Resampling.LANCZOS,centering=(0.5,a.focus))
 im=ImageEnhance.Contrast(ImageEnhance.Color(im).enhance(a.saturation)).enhance(a.contrast)
 inks=dither(im)
 frame=bytes((inks[i]<<4)|inks[i+1] for i in range(0,len(inks),2))
 assert len(frame)==800*480//2
 caption=a.caption.replace('\\','').replace('"','')
 lines=['// Generated by tools/generate_privacy.py; picture: '+a.source,'// '+a.licence,'#include "privacy.h"',
  f'const char privacy_caption[]="{caption}";','const uint8_t privacy_frame[FRAME_BYTES]={']
 lines+=[','.join(f'0x{b:02x}' for b in frame[i:i+32])+',' for i in range(0,len(frame),32)]+['};']
 (ROOT/'main/privacy.c').write_text('\n'.join(lines)+'\n')
 out=ROOT/'artifacts/ui-preview';out.mkdir(parents=True,exist_ok=True)
 Image.frombytes('RGB',(800,480),bytes(c for k in inks for c in PREVIEW[k])).save(out/'privacy-picture.png')
 (ROOT/'artifacts/privacy-picture.json').write_text(json.dumps({'source':a.source,'licence':a.licence,'caption':caption,
  'source_sha256':hashlib.sha256(raw).hexdigest(),'source_bytes':len(raw),'crop':'centre-fit 800x480, vertical focus %.2f'%a.focus,
  'saturation':a.saturation,'contrast':a.contrast,'dither':'serpentine Floyd-Steinberg to six inks','source_kept_in_repo':False},ensure_ascii=False,indent=2)+'\n')
 print('privacy frame written:',caption)
